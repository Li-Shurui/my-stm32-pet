#!/usr/bin/env python3
# gen_kaomoji.py - render kaomoji to alpha bitmaps and emit src/kaomoji_data.h
#
# Each kaomoji is rendered with a per-character font fallback chain, tightly
# cropped, and stored as an 8-bit alpha channel (the pet draws the text in a
# fixed warm-white colour, so only coverage is needed).
import os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
FONTS = [
    r"C:\Windows\Fonts\msgothic.ttc",
    r"C:\Windows\Fonts\msyh.ttc",
    r"C:\Windows\Fonts\simsun.ttc",
    r"C:\Windows\Fonts\seguisym.ttf",
]
SIZE = 26

# mood-tagged kaomoji (all glyphs verified against the font chain)
KAOMOJI = [
    ("(=^･ω･^=)", "greet"),
    ("(＾▽＾)", "happy"),
    ("(´▽｀)", "happy"),
    ("(￣▽￣)", "happy"),
    ("(♥ω♥*)", "love"),
    ("(｡• ω •｡)", "cute"),
    ("(╹◡╹)♥", "cute"),
    ("(－_－)", "sleepy"),
    ("(oT-T)尸", "sleepy"),
    ("(￣ー￣)", "sleepy"),
    ("(・_・?)", "hmm"),
    ("(ﾟﾛﾟ)", "hmm"),
    ("(・。・;)", "hmm"),
    ("(¬‿¬)", "smug"),
    ("(￣ω￣;)", "smug"),
    ("(￣^￣)", "smug"),
    ("(>_<)", "angry"),
    ("(＃￣0￣)", "angry"),
    ("(＃＞＜)", "angry"),
    ("(¬､¬)", "sad"),
    ("(x_x)", "sad"),
    ("(⊙_⊙)", "shock"),
    ("(╬☉д⊙)", "shock"),
    ("(屮゜Д゜)屮", "shock"),
    ("(ﾉ◕ヮ◕)ﾉ", "cheer"),
]

_cache = {}

def get_font(path):
    if path not in _cache:
        _cache[path] = ImageFont.truetype(path, SIZE)
    return _cache[path]

def glyph_mask(font, ch):
    return bytes(font.getmask(ch))

def pick_font(ch):
    ctrl = None
    for p in FONTS:
        f = get_font(p)
        if ctrl is None:
            ctrl = glyph_mask(f, "\uE123")
        if glyph_mask(f, ch) != ctrl:
            return f
    return None

def draw_string(draw, xy, s, fill):
    x, y = xy
    for ch in s:
        f = pick_font(ch)
        if f is None:
            raise SystemExit(f"FATAL: no font has glyph for {ch!r} (U+{ord(ch):04X})")
        draw.text((x, y), ch, font=f, fill=fill)
        x += f.getlength(ch)

def render(text):
    """Render one kaomoji, return (w, h, alpha_bytes) tightly cropped."""
    pad = 8
    w = int(sum((pick_font(c).getlength(c) for c in text), 0)) + pad * 2
    img = Image.new("L", (max(w, 16), SIZE + pad * 2), 0)
    d = ImageDraw.Draw(img)
    draw_string(d, (pad, pad), text, 255)
    bbox = img.getbbox()
    if not bbox:
        raise SystemExit(f"FATAL: empty render for {text!r}")
    img = img.crop(bbox)
    return img.width, img.height, img.tobytes()

def main():
    out_h = os.path.join(HERE, "..", "src", "kaomoji_data.h")
    entries = []
    total = 0
    sheet = Image.new("RGBA", (760, 40 * (len(KAOMOJI) + 1)), (24, 26, 34, 255))
    ds = ImageDraw.Draw(sheet)

    for i, (text, mood) in enumerate(KAOMOJI):
        w, h, alpha = render(text)
        total += len(alpha)
        name = f"km_{i}"
        entries.append((name, w, h, mood, text))
        with open(os.path.join(HERE, "..", "src", f"{name}.alpha"), "wb") as f:
            f.write(alpha)
        ds.text((8, 40 * (i + 1) + 8), f"{i:2d} {mood:7s}", fill=(120, 130, 150))
        # draw preview in warm white
        pv = Image.frombytes("L", (w, h), alpha)
        sheet.paste(Image.new("RGBA", (w, h), (255, 250, 240, 255)),
                    (150, 40 * (i + 1) + 6), pv)

    with open(out_h, "w", encoding="utf-8") as f:
        f.write("/* kaomoji_data.h - auto-generated by tools/gen_kaomoji.py\n")
        f.write(f" * {len(entries)} alpha bitmaps, mood-tagged. Do not edit. */\n")
        f.write("#ifndef KAOMOJI_DATA_H\n#define KAOMOJI_DATA_H\n\n")
        f.write("typedef struct { int w, h; const unsigned char *a; const char *mood; const char *text; } kaomoji_t;\n\n")
        for name, w, h, mood, text in entries:
            data = open(os.path.join(HERE, "..", "src", f"{name}.alpha"), "rb").read()
            f.write(f"static const unsigned char {name}[{len(data)}] = {{\n")
            for j in range(0, len(data), 20):
                f.write("    " + ",".join(str(b) for b in data[j:j + 20]) + ",\n")
            f.write("};\n")
            os.remove(os.path.join(HERE, "..", "src", f"{name}.alpha"))
        f.write("\nstatic const kaomoji_t kaomoji_list[] = {\n")
        for name, w, h, mood, text in entries:
            esc = text.replace("\\", "\\\\").replace('"', '\\"')
            f.write(f'    {{ {w}, {h}, {name}, "{mood}", "{esc}" }},\n')
        f.write("};\n\n")
        f.write(f"#define KAOMOJI_COUNT {len(entries)}\n\n")
        f.write("#endif /* KAOMOJI_DATA_H */\n")

    sheet.save(os.path.join(HERE, "kaomoji_final_preview.png"))
    print(f"kaomoji: {len(entries)}, alpha bytes: {total} ({total//1024} KB)")
    print("wrote", os.path.abspath(out_h))
    print("preview:", os.path.abspath(os.path.join(HERE, "kaomoji_final_preview.png")))

if __name__ == "__main__":
    main()
